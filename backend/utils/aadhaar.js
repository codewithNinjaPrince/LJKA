// Aadhaar numbers use the Verhoeff check digit. This only validates format
// and checksum; UIDAI verification still requires its authorised process.
export const isValidAadhaar = (value) => {
  const aadhaar = String(value || "").trim();
  if (!/^[2-9]\d{11}$/.test(aadhaar)) return false;

  let check = 0;
  [...aadhaar].reverse().forEach((digit, index) => {
    check = multiplication[check][permutation[index % 8][Number(digit)]];
  });
  return check === 0;
};

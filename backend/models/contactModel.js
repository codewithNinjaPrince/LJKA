import mongoose from "mongoose";

const contactSchema = new mongoose.Schema(
  {
    name: {
      type: String,
      required: true,
      trim: true,
    },

    email: {
      type: String,
      trim: true,
      lowercase: true,
      default: "",
    },

    phone: {
      type: String,
      required: true,
      trim: true,
    },

    subject: {
      type: String,
      required: true,
      trim: true,
    },

    message: {
      type: String,
      required: true,
      trim: true,
    },

    status: {
      type: String,
      enum: ["new", "read", "in_progress", "resolved"],
      default: "new",
    },
  },
  {
    timestamps: true,
  }
);

const ContactModel =
  mongoose.models.Contact ||
  mongoose.model("Contact", contactSchema);

export default ContactModel;